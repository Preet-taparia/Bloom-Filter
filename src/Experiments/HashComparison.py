"""Matched workloads for library-backed standard and counting Bloom filters."""
import csv
import json
import platform
import random
import statistics
import sys
import time
from pathlib import Path

from .Figures import plt
from ..bloom.standard import BloomFilter
from ..bloom.CountingBloomFilter import CountingBloomFilter
from ..bloom.theory import optimal_hash_count


def compare(algorithms, out_dir: Path, items=2000, queries=10000, trials=3, *, filter_type="standard", counter_bits=4):
    if filter_type not in ("standard", "counting"):
        raise ValueError("filter_type must be standard or counting")
    counting = filter_type == "counting"
    filter_class = CountingBloomFilter if counting else BloomFilter
    options = {"counter_bits": counter_bits} if counting else {}
    prefix = "counting_hash" if counting else "hash"
    ratio_key = "slots_per_item" if counting else "bits_per_item"
    rows = []
    for trial in range(trials):
        members = [f'member-{trial}-{i}' for i in range(items)]
        probes = [f'absent-{trial}-{i}' for i in range(queries)]
        order = list(algorithms)
        random.Random(trial).shuffle(order)
        for ratio in (4, 8, 12, 16):
            for algorithm in order:
                bloom = filter_class(items*ratio, optimal_hash_count(items*ratio, items), seed=trial, hash_algorithm=algorithm, **options)
                # Time insertion plus present and absent membership queries.
                # Input generation, allocation and report writing are excluded.
                start = time.perf_counter()
                bloom.update(members)
                misses = sum(x not in bloom for x in members)
                false_positives = sum(x in bloom for x in probes)
                execution_time_ms = (time.perf_counter()-start)*1000
                if misses:
                    raise AssertionError(f"{algorithm}: {misses} false negatives")
                rows.append(dict(algorithm=algorithm, trial=trial, seed=trial, items=items, queries=queries,
                    **{ratio_key: ratio}, slots=bloom.size, hash_count=bloom.hash_count,
                    false_positive_rate=false_positives/queries,
                    execution_time_ms=execution_time_ms))
                print(f'{algorithm}: trial {trial+1}/{trials}, m/n={ratio}, FP={false_positives/queries:.5f}', flush=True)
    csv_dir = out_dir/'csv'; csv_dir.mkdir(parents=True, exist_ok=True)
    with (csv_dir/f'{prefix}_trials.csv').open('w', newline='') as handle:
        writer = csv.DictWriter(handle, fieldnames=rows[0]); writer.writeheader(); writer.writerows(rows)
    metrics = ('false_positive_rate', 'execution_time_ms')
    summary = []
    for algorithm in algorithms:
        for ratio in (4, 8, 12, 16):
            group = [r for r in rows if r['algorithm']==algorithm and r[ratio_key]==ratio]
            result = dict(algorithm=algorithm, **{ratio_key: ratio})
            for metric in metrics:
                values = [r[metric] for r in group]
                result[metric+'_mean'] = statistics.mean(values)
                result[metric+'_std'] = statistics.pstdev(values)
            summary.append(result)
    with (csv_dir/f'{prefix}_summary.csv').open('w', newline='') as handle:
        writer = csv.DictWriter(handle, fieldnames=summary[0]); writer.writeheader(); writer.writerows(summary)
    figures = out_dir/'figures'; figures.mkdir(parents=True, exist_ok=True)
    # Remove only obsolete plots previously generated by this comparison.
    for metric in ('theoretical_rate', 'fill_ratio', 'logical_bytes', 'storage_bytes',
                   'hash_pair_collisions', 'false_negatives', 'hash_ns', 'insert_ns',
                   'present_query_ns', 'absent_query_ns'):
        (figures/f'{prefix}_{metric}.png').unlink(missing_ok=True)
    for metric in metrics:
        fig, ax = plt.subplots(figsize=(8, 5))
        for algorithm in algorithms:
            group = [r for r in summary if r['algorithm']==algorithm]
            ax.errorbar([r[ratio_key] for r in group], [r[metric+'_mean'] for r in group], yerr=[r[metric+'_std'] for r in group], marker='o', capsize=3, label=algorithm)
        ax.set(xlabel='Counter slots per inserted item' if counting else 'Bits per inserted item', ylabel=metric.replace('_', ' '), title=('Counting Bloom filter — ' if counting else '')+metric.replace('_', ' ').title()+' — library implementation (mean ± trial SD)')
        ax.legend(); ax.grid(alpha=.3); fig.tight_layout(); fig.savefig(figures/f'{prefix}_{metric}.png', dpi=150); plt.close(fig)
    (out_dir/f'{prefix}_metadata.json').write_text(json.dumps(dict(filter_type=filter_type, counter_bits=counter_bits if counting else None, python=sys.version, platform=platform.platform(), algorithms=list(algorithms), items=items, queries=queries, trials=trials, implementation='MurmurHash3 x86-32 and xxHash32: two seeded native-backed mmh3/xxhash hashes; FNV-1a 64: two domain-prefixed native-backed fnv-c hashes; MD5 and BLAKE2b: hashlib digests split into two 64-bit words. BLAKE2b uses the original seed salt; other hashes include the seed in input. Execution time in milliseconds covers insertion and all present/absent queries, excluding input generation, allocation and output. Timings are implementation-specific.'), indent=2))
    return out_dir
